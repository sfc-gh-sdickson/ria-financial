-- ============================================================================
-- ML FEATURE VIEWS. One view per model family is the single source of truth for
-- training (notebooks/07_ml_models.py) and scoring. Feature columns are every
-- column except the key, time and label columns named in the notebook. All
-- features are FLOAT with NULLs removed by COALESCE. Prior-activity features
-- look only backwards in time, so no label information leaks into them.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- Transfer-level base features (models 1, 7, 8)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW V_TRANSFER_BASE AS
WITH dev AS (
    SELECT DEVICE_ID, COUNT(DISTINCT CUSTOMER_ID) AS DEVICE_CUSTOMERS FROM RIA_FINANCIAL_INTELLIGENCE.RAW.APP_SESSIONS GROUP BY DEVICE_ID
),
w AS (
    SELECT t.*,
        COUNT(*) OVER (PARTITION BY t.CUSTOMER_ID ORDER BY t.CREATED_AT, t.TRANSFER_ID ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING) AS W_PRIOR_COUNT,
        AVG(t.SEND_AMOUNT_USD) OVER (PARTITION BY t.CUSTOMER_ID ORDER BY t.CREATED_AT, t.TRANSFER_ID ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING) AS W_PRIOR_AVG,
        COUNT(*) OVER (PARTITION BY t.CUSTOMER_ID ORDER BY DATE_PART(EPOCH_SECOND, t.CREATED_AT) RANGE BETWEEN 86400 PRECEDING AND 1 PRECEDING) AS W_PRIOR_24H_COUNT,
        SUM(t.SEND_AMOUNT_USD) OVER (PARTITION BY t.CUSTOMER_ID ORDER BY DATE_PART(EPOCH_SECOND, t.CREATED_AT) RANGE BETWEEN 86400 PRECEDING AND 1 PRECEDING) AS W_PRIOR_24H_USD,
        SUM(t.SEND_AMOUNT_USD) OVER (PARTITION BY t.CUSTOMER_ID ORDER BY DATE_PART(EPOCH_SECOND, t.CREATED_AT) RANGE BETWEEN 604800 PRECEDING AND 1 PRECEDING) AS W_PRIOR_7D_USD,
        COUNT(*) OVER (PARTITION BY t.CUSTOMER_ID, t.BENEFICIARY_ID ORDER BY t.CREATED_AT, t.TRANSFER_ID ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING) AS W_BENE_BY_CUST,
        COUNT(*) OVER (PARTITION BY t.BENEFICIARY_ID ORDER BY t.CREATED_AT, t.TRANSFER_ID ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING) AS W_BENE_ALL
    FROM RIA_FINANCIAL_INTELLIGENCE.RAW.TRANSFERS t
)
SELECT w.TRANSFER_ID, w.CUSTOMER_ID, w.CREATED_AT,
    w.SEND_AMOUNT_USD::FLOAT AS AMOUNT_USD,
    HOUR(w.CREATED_AT)::FLOAT AS HOUR_OF_DAY,
    IFF(HOUR(w.CREATED_AT) < 6 OR HOUR(w.CREATED_AT) >= 22, 1, 0)::FLOAT AS IS_NIGHT,
    IFF(DAYOFWEEK(w.CREATED_AT) IN (0, 6), 1, 0)::FLOAT AS IS_WEEKEND,
    IFF(w.CHANNEL <> 'Retail Agent', 1, 0)::FLOAT AS IS_DIGITAL,
    IFF(w.CHANNEL = 'Mobile App', 1, 0)::FLOAT AS IS_APP,
    IFF(w.CHANNEL = 'Web', 1, 0)::FLOAT AS IS_WEB,
    IFF(w.FUNDING_TYPE = 'Cash', 1, 0)::FLOAT AS FUND_CASH,
    IFF(w.FUNDING_TYPE = 'Debit Card', 1, 0)::FLOAT AS FUND_DEBIT,
    IFF(w.FUNDING_TYPE = 'Credit Card', 1, 0)::FLOAT AS FUND_CREDIT,
    IFF(w.FUNDING_TYPE = 'Bank Account', 1, 0)::FLOAT AS FUND_BANK,
    IFF(w.PAYOUT_METHOD = 'Cash Pickup', 1, 0)::FLOAT AS PAYOUT_CASH,
    IFF(w.PAYOUT_METHOD = 'Bank Deposit', 1, 0)::FLOAT AS PAYOUT_BANK,
    IFF(w.PAYOUT_METHOD = 'Mobile Wallet', 1, 0)::FLOAT AS PAYOUT_WALLET,
    co.CORRIDOR_RISK_SCORE::FLOAT AS CORRIDOR_RISK_SCORE,
    IFF(co.IS_HIGH_RISK_JURISDICTION, 1, 0)::FLOAT AS HIGH_RISK_JURISDICTION,
    IFF(w.SEND_AMOUNT_USD BETWEEN 2500 AND 2999.99, 1, 0)::FLOAT AS IS_NEAR_3K,
    IFF(w.SEND_AMOUNT_USD BETWEEN 8500 AND 9999.99, 1, 0)::FLOAT AS IS_NEAR_10K,
    DATEDIFF(DAY, c.SIGNUP_DATE, w.CREATED_AT::DATE)::FLOAT AS CUSTOMER_TENURE_DAYS,
    DATEDIFF(YEAR, c.DATE_OF_BIRTH, w.CREATED_AT::DATE)::FLOAT AS CUSTOMER_AGE_YEARS,
    COALESCE(w.W_PRIOR_COUNT, 0)::FLOAT AS PRIOR_TRANSFER_COUNT,
    COALESCE(w.SEND_AMOUNT_USD / NULLIF(w.W_PRIOR_AVG, 0), 1.0)::FLOAT AS AMOUNT_VS_AVG_RATIO,
    COALESCE(w.W_PRIOR_24H_COUNT, 0)::FLOAT AS TRANSFERS_PRIOR_24H,
    COALESCE(w.W_PRIOR_24H_USD, 0)::FLOAT AS USD_PRIOR_24H,
    COALESCE(w.W_PRIOR_7D_USD, 0)::FLOAT AS USD_PRIOR_7D,
    COALESCE(w.W_BENE_BY_CUST, 0)::FLOAT AS BENE_PRIOR_BY_CUSTOMER,
    IFF(COALESCE(w.W_BENE_BY_CUST, 0) = 0, 1, 0)::FLOAT AS IS_NEW_BENEFICIARY,
    GREATEST(0, DATEDIFF(HOUR, b.CREATED_AT, w.CREATED_AT))::FLOAT AS BENE_AGE_HOURS,
