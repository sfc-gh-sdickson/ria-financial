-- ============================================================================
-- Customer-level model score roll-up
-- ============================================================================
CREATE OR REPLACE VIEW CUSTOMER_MODEL_SCORES AS
SELECT c.CUSTOMER_ID,
    sy.SYNTHETIC_PROB AS SYNTHETIC_ID_PROBABILITY, sy.RISK_TIER AS SYNTHETIC_ID_TIER,
    ato.MAX_PROB AS ATO_MAX_PROBABILITY_30D, ato.TIER AS ATO_TIER_30D,
    tf.MAX_PROB AS TRANSFER_FRAUD_MAX_PROBABILITY_90D, tf.TIER AS TRANSFER_FRAUD_TIER_90D,
    st.MAX_PROB AS STRUCTURING_MAX_PROBABILITY_8W, st.TIER AS STRUCTURING_TIER_8W,
    rg.ANOMALY_SCORE AS RING_ANOMALY_SCORE, rg.CLUSTER_ID AS RING_CLUSTER_ID, rg.CLUSTER_SIZE AS RING_CLUSTER_SIZE, rg.RISK_TIER AS RING_TIER,
    CASE GREATEST(COALESCE(CASE sy.RISK_TIER WHEN 'High' THEN 3 WHEN 'Medium' THEN 2 WHEN 'Low' THEN 1 END, 0),
                  COALESCE(CASE ato.TIER WHEN 'High' THEN 3 WHEN 'Medium' THEN 2 WHEN 'Low' THEN 1 END, 0),
                  COALESCE(CASE tf.TIER WHEN 'High' THEN 3 WHEN 'Medium' THEN 2 WHEN 'Low' THEN 1 END, 0),
                  COALESCE(CASE st.TIER WHEN 'High' THEN 3 WHEN 'Medium' THEN 2 WHEN 'Low' THEN 1 END, 0),
                  COALESCE(CASE rg.RISK_TIER WHEN 'High' THEN 3 WHEN 'Medium' THEN 2 WHEN 'Low' THEN 1 END, 0))
         WHEN 3 THEN 'High' WHEN 2 THEN 'Medium' WHEN 1 THEN 'Low' ELSE 'Not scored' END AS COMPOSITE_MODEL_RISK_TIER
FROM RIA_FINANCIAL_INTELLIGENCE.RAW.CUSTOMERS c
LEFT JOIN SYNTHETIC_ID_SCORES sy ON sy.CUSTOMER_ID = c.CUSTOMER_ID
LEFT JOIN (SELECT CUSTOMER_ID, MAX(ATO_PROB) AS MAX_PROB, MAX_BY(RISK_TIER, ATO_PROB) AS TIER FROM ATO_SESSION_SCORES
           WHERE LOGIN_AT >= DATEADD(DAY, -30, CURRENT_TIMESTAMP()) GROUP BY CUSTOMER_ID) ato ON ato.CUSTOMER_ID = c.CUSTOMER_ID
LEFT JOIN (SELECT CUSTOMER_ID, MAX(FRAUD_PROB) AS MAX_PROB, MAX_BY(RISK_TIER, FRAUD_PROB) AS TIER FROM TRANSFER_FRAUD_SCORES
           WHERE CREATED_AT >= DATEADD(DAY, -90, CURRENT_TIMESTAMP()) GROUP BY CUSTOMER_ID) tf ON tf.CUSTOMER_ID = c.CUSTOMER_ID
LEFT JOIN (SELECT CUSTOMER_ID, MAX(STRUCTURING_PROB) AS MAX_PROB, MAX_BY(RISK_TIER, STRUCTURING_PROB) AS TIER FROM STRUCTURING_SCORES
           WHERE WEEK_START >= DATEADD(WEEK, -8, CURRENT_DATE()) GROUP BY CUSTOMER_ID) st ON st.CUSTOMER_ID = c.CUSTOMER_ID
LEFT JOIN FRAUD_RING_SCORES rg ON rg.CUSTOMER_ID = c.CUSTOMER_ID;

-- ============================================================================
-- FRAUD RING clusters (shared phone / device / IP / beneficiary links)
-- ============================================================================
CREATE OR REPLACE VIEW FRAUD_RING_CLUSTERS AS
SELECT r.CLUSTER_ID, MAX(r.CLUSTER_SIZE) AS ACCOUNTS_LINKED, MAX(r.CLUSTER_SCORE) AS CLUSTER_ANOMALY_SCORE, MAX_BY(r.RISK_TIER, r.CLUSTER_SCORE) AS CLUSTER_RISK_TIER,
    LISTAGG(r.CUSTOMER_ID, ', ') WITHIN GROUP (ORDER BY r.ANOMALY_SCORE DESC) AS MEMBER_CUSTOMER_IDS,
    SUM(COALESCE(v.VOLUME_90D, 0)) AS VOLUME_90D_USD, SUM(COALESCE(v.VOLUME_ALL, 0)) AS VOLUME_ALL_USD,
    SUM(COALESCE(cs.OPEN_CASES, 0)) AS OPEN_CASES, SUM(COALESCE(cs.RING_CASES, 0)) AS RING_CASES
FROM FRAUD_RING_SCORES r
LEFT JOIN (SELECT CUSTOMER_ID, SUM(IFF(CREATED_AT >= DATEADD(DAY, -90, CURRENT_TIMESTAMP()), SEND_AMOUNT_USD, 0)) AS VOLUME_90D, SUM(SEND_AMOUNT_USD) AS VOLUME_ALL
           FROM RIA_FINANCIAL_INTELLIGENCE.RAW.TRANSFERS GROUP BY CUSTOMER_ID) v ON v.CUSTOMER_ID = r.CUSTOMER_ID
LEFT JOIN (SELECT CUSTOMER_ID, COUNT_IF(STATUS <> 'Closed') AS OPEN_CASES, COUNT_IF(CASE_TYPE = 'Fraud Ring') AS RING_CASES
           FROM RIA_FINANCIAL_INTELLIGENCE.RAW.FRAUD_CASES GROUP BY CUSTOMER_ID) cs ON cs.CUSTOMER_ID = r.CUSTOMER_ID
WHERE r.CLUSTER_SIZE >= 3
GROUP BY r.CLUSTER_ID;

