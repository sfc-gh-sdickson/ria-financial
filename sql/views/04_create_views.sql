JOIN (SELECT t.SEND_AGENT_ID, COUNT(*) AS N, SUM(t.SEND_AMOUNT_USD) AS TOTAL_USD, AVG(t.SEND_AMOUNT_USD) AS AVG_USD,
             AVG(IFF(t.SEND_AMOUNT_USD BETWEEN 2500 AND 2999.99, 1, 0)) AS NEAR_3K_SHARE, AVG(IFF(t.SEND_AMOUNT_USD BETWEEN 8500 AND 9999.99, 1, 0)) AS NEAR_10K_SHARE,
