-- Model 10: sanctions screening hit triage (label NULL while the hit is open)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW V_SCREENING_FEATURES AS
SELECT sc.SCREENING_ID, sc.CUSTOMER_ID,
    sc.MATCH_SCORE::FLOAT AS MATCH_SCORE, sc.NAME_SIMILARITY::FLOAT AS NAME_SIMILARITY,
    IFF(sc.DOB_MATCH, 1, 0)::FLOAT AS DOB_MATCH, IFF(sc.COUNTRY_MATCH, 1, 0)::FLOAT AS COUNTRY_MATCH, IFF(sc.SECONDARY_ID_MATCH, 1, 0)::FLOAT AS SECONDARY_ID_MATCH,
    IFF(sc.LIST_SOURCE = 'SDN', 1, 0)::FLOAT AS LIST_SDN, IFF(sc.LIST_SOURCE = 'EU', 1, 0)::FLOAT AS LIST_EU, IFF(sc.LIST_SOURCE = 'UN', 1, 0)::FLOAT AS LIST_UN,
    IFF(sc.LIST_SOURCE = 'UK HMT', 1, 0)::FLOAT AS LIST_UK_HMT, IFF(sc.SCREENED_PARTY = 'Sender', 1, 0)::FLOAT AS PARTY_IS_SENDER,
    t.SEND_AMOUNT_USD::FLOAT AS AMOUNT_USD, co.CORRIDOR_RISK_SCORE::FLOAT AS CORRIDOR_RISK_SCORE, IFF(co.IS_HIGH_RISK_JURISDICTION, 1, 0)::FLOAT AS HIGH_RISK_JURISDICTION,
    CASE k.RISK_RATING WHEN 'High' THEN 3 WHEN 'Medium' THEN 2 ELSE 1 END::FLOAT AS KYC_RISK_NUM, IFF(k.PEP_FLAG, 1, 0)::FLOAT AS PEP_FLAG,
    DATEDIFF(DAY, c.SIGNUP_DATE, sc.SCREENED_AT::DATE)::FLOAT AS CUSTOMER_TENURE_DAYS,
    sc.IS_TRUE_MATCH::INT AS IS_TRUE_MATCH
FROM RIA_FINANCIAL_INTELLIGENCE.RAW.SANCTIONS_SCREENING sc
JOIN RIA_FINANCIAL_INTELLIGENCE.RAW.TRANSFERS t ON t.TRANSFER_ID = sc.TRANSFER_ID
JOIN RIA_FINANCIAL_INTELLIGENCE.RAW.CORRIDORS co ON co.CORRIDOR_ID = t.CORRIDOR_ID
JOIN RIA_FINANCIAL_INTELLIGENCE.RAW.CUSTOMERS c ON c.CUSTOMER_ID = sc.CUSTOMER_ID
JOIN RIA_FINANCIAL_INTELLIGENCE.RAW.KYC_PROFILES k ON k.CUSTOMER_ID = sc.CUSTOMER_ID;
