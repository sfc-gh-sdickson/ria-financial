USE WAREHOUSE RIA_FINANCIAL_WH;

-- ============================================================================
-- MODEL SCORE TABLES. Created IF NOT EXISTS so re-running step 3 or 4 never
-- drops scores. python3 notebooks/07_ml_models.py truncates and refills them.
-- Every number in these tables is a model prediction trained on synthetic data.
-- ============================================================================
CREATE TABLE IF NOT EXISTS TRANSFER_FRAUD_SCORES (
    TRANSFER_ID VARCHAR(20), CUSTOMER_ID VARCHAR(20), CREATED_AT TIMESTAMP_NTZ, SCORED_AT TIMESTAMP_NTZ,
    FRAUD_PROB FLOAT, RISK_TIER VARCHAR(10)
) COMMENT = 'Model 1: transaction fraud probability per transfer from the last 180 days (model prediction, synthetic training data)';

CREATE TABLE IF NOT EXISTS ATO_SESSION_SCORES (
    SESSION_ID VARCHAR(20), CUSTOMER_ID VARCHAR(20), LOGIN_AT TIMESTAMP_NTZ, SCORED_AT TIMESTAMP_NTZ,
    ATO_PROB FLOAT, RISK_TIER VARCHAR(10)
) COMMENT = 'Model 2: account-takeover probability per login session from the last 180 days (model prediction)';

CREATE TABLE IF NOT EXISTS SYNTHETIC_ID_SCORES (
    CUSTOMER_ID VARCHAR(20), SIGNUP_DATE DATE, SCORED_AT TIMESTAMP_NTZ, SYNTHETIC_PROB FLOAT, RISK_TIER VARCHAR(10)
) COMMENT = 'Model 3: synthetic-identity probability per customer (model prediction)';

CREATE TABLE IF NOT EXISTS MULE_SCORES (
    BENEFICIARY_ID VARCHAR(20), SCORED_AT TIMESTAMP_NTZ, MULE_PROB FLOAT, RISK_TIER VARCHAR(10)
) COMMENT = 'Model 4: money-mule probability per beneficiary (model prediction)';

CREATE TABLE IF NOT EXISTS STRUCTURING_SCORES (
    CUSTOMER_ID VARCHAR(20), WEEK_START DATE, SCORED_AT TIMESTAMP_NTZ, STRUCTURING_PROB FLOAT, RISK_TIER VARCHAR(10)
) COMMENT = 'Model 5: structuring probability per customer-week with $3,000 or more sent (model prediction)';

CREATE TABLE IF NOT EXISTS AGENT_COLLUSION_SCORES (
    AGENT_ID VARCHAR(20), SCORED_AT TIMESTAMP_NTZ, COLLUSION_PROB FLOAT, RISK_TIER VARCHAR(10)
) COMMENT = 'Model 6: collusion probability per agent location (model prediction)';

CREATE TABLE IF NOT EXISTS CHARGEBACK_SCORES (
    TRANSFER_ID VARCHAR(20), CUSTOMER_ID VARCHAR(20), CREATED_AT TIMESTAMP_NTZ, SCORED_AT TIMESTAMP_NTZ,
    AMOUNT_USD FLOAT, CHARGEBACK_PROB FLOAT, EXPECTED_CHARGEBACK_USD FLOAT, RISK_TIER VARCHAR(10)
) COMMENT = 'Model 7: probability of a chargeback within 90 days per card-funded transfer from the last 180 days (model prediction)';

CREATE TABLE IF NOT EXISTS SCAM_SCORES (
    TRANSFER_ID VARCHAR(20), CUSTOMER_ID VARCHAR(20), CREATED_AT TIMESTAMP_NTZ, SCORED_AT TIMESTAMP_NTZ,
    SCAM_PROB FLOAT, RISK_TIER VARCHAR(10)
) COMMENT = 'Model 8: scam-victim probability per transfer from the last 180 days (model prediction)';

CREATE TABLE IF NOT EXISTS FRAUD_RING_SCORES (
    CUSTOMER_ID VARCHAR(20), SCORED_AT TIMESTAMP_NTZ, ANOMALY_SCORE FLOAT, CLUSTER_ID VARCHAR(20), CLUSTER_SIZE INTEGER,
    CLUSTER_SCORE FLOAT, RISK_TIER VARCHAR(10)
) COMMENT = 'Model 9: unsupervised network-anomaly score per customer with cluster id, size and cluster-level score (model prediction)';

CREATE TABLE IF NOT EXISTS SCREENING_TRIAGE_SCORES (
    SCREENING_ID VARCHAR(20), SCORED_AT TIMESTAMP_NTZ, TRUE_MATCH_PROB FLOAT, RISK_TIER VARCHAR(10)
) COMMENT = 'Model 10: true-match probability per sanctions screening hit (model prediction)';

CREATE TABLE IF NOT EXISTS RIA_FINANCIAL_INTELLIGENCE.ML.MODEL_REGISTRY (
    MODEL_ID INTEGER, MODEL_NAME VARCHAR(100), MODEL_TYPE VARCHAR(40), ALGORITHM VARCHAR(60), TARGET VARCHAR(100),
    REGISTRY_MODEL_NAME VARCHAR(100), VERSION VARCHAR(40), MODEL_OWNER VARCHAR(80), TRAINING_DATE DATE, TRAINING_ROWS INTEGER,
    POSITIVE_RATE FLOAT, ROC_AUC FLOAT, PR_AUC FLOAT, VALIDATION_STATUS VARCHAR(40), LAST_VALIDATION_DATE DATE,
    NEXT_VALIDATION_DATE DATE, INTENDED_USE VARCHAR(400), LIMITATIONS VARCHAR(600), HIGH_THRESHOLD FLOAT, MEDIUM_THRESHOLD FLOAT,
    SCORE_TABLE VARCHAR(100), AGENT_TOOL VARCHAR(60), METRIC_NOTE VARCHAR(400)
) COMMENT = 'SR 11-7 / OCC 2011-12 model inventory for the 10 Ria fraud and compliance models. Metrics come from synthetic data';

-- ============================================================================
-- MASKED CUSTOMER PROFILE (GLBA): initials, masked email, last 4 of phone, age only
-- ============================================================================
CREATE OR REPLACE VIEW CUSTOMER_PROFILE AS
SELECT c.CUSTOMER_ID,
    LEFT(c.FIRST_NAME, 1) || '*** ' || LEFT(c.LAST_NAME, 1) || '***' AS CUSTOMER_NAME_MASKED,
    'c***@' || SPLIT_PART(c.EMAIL, '@', 2) AS EMAIL_MASKED,
    '***-***-' || RIGHT(c.PHONE, 4) AS PHONE_MASKED,
    DATEDIFF(YEAR, c.DATE_OF_BIRTH, CURRENT_DATE()) AS AGE_YEARS,
    CASE WHEN DATEDIFF(YEAR, c.DATE_OF_BIRTH, CURRENT_DATE()) < 25 THEN '18-24'
         WHEN DATEDIFF(YEAR, c.DATE_OF_BIRTH, CURRENT_DATE()) < 40 THEN '25-39'
         WHEN DATEDIFF(YEAR, c.DATE_OF_BIRTH, CURRENT_DATE()) < 60 THEN '40-59'
         WHEN DATEDIFF(YEAR, c.DATE_OF_BIRTH, CURRENT_DATE()) < 65 THEN '60-64' ELSE '65+' END AS AGE_BAND,
    c.COUNTRY_OF_RESIDENCE, c.CITY, c.NATIONALITY, c.SIGNUP_DATE, DATE_TRUNC('MONTH', c.SIGNUP_DATE) AS SIGNUP_MONTH,
    DATEDIFF(DAY, c.SIGNUP_DATE, CURRENT_DATE()) AS TENURE_DAYS, c.SIGNUP_CHANNEL, c.HOME_AGENT_ID,
    c.PREFERRED_CORRIDOR_ID, co.CORRIDOR_NAME AS PREFERRED_CORRIDOR_NAME, c.SEGMENT, c.LOYALTY_TIER, c.STATUS, c.MARKETING_OPT_IN
FROM RIA_FINANCIAL_INTELLIGENCE.RAW.CUSTOMERS c
JOIN RIA_FINANCIAL_INTELLIGENCE.RAW.CORRIDORS co ON co.CORRIDOR_ID = c.PREFERRED_CORRIDOR_ID;

-- ============================================================================
-- KYC / CDD / EDD detail with synthetic-identity score
-- ============================================================================
CREATE OR REPLACE VIEW KYC_DETAIL AS
SELECT k.CUSTOMER_ID, p.CUSTOMER_NAME_MASKED, p.SEGMENT, p.COUNTRY_OF_RESIDENCE, p.SIGNUP_DATE, p.SIGNUP_MONTH, p.SIGNUP_CHANNEL, p.AGE_BAND, p.STATUS AS CUSTOMER_STATUS,
    k.KYC_TIER, k.RISK_RATING, k.PEP_FLAG, k.EDD_REQUIRED, k.EDD_COMPLETED, (k.EDD_REQUIRED AND NOT k.EDD_COMPLETED) AS EDD_OUTSTANDING,
    k.ID_DOCUMENT_TYPE, k.ID_VERIFICATION_STATUS, k.ID_VERIFICATION_ATTEMPTS, k.SOURCE_OF_FUNDS, k.OCCUPATION, k.EXPECTED_MONTHLY_USD,
    k.LAST_REVIEW_DATE, k.NEXT_REVIEW_DATE, (k.NEXT_REVIEW_DATE < CURRENT_DATE()) AS REVIEW_OVERDUE,
    GREATEST(0, DATEDIFF(DAY, k.NEXT_REVIEW_DATE, CURRENT_DATE())) AS DAYS_REVIEW_OVERDUE,
    k.EMAIL_AGE_DAYS, k.PHONE_IS_VOIP, k.ADDRESS_SHARED_COUNT,
    s.SYNTHETIC_PROB AS SYNTHETIC_ID_PROBABILITY, s.RISK_TIER AS SYNTHETIC_ID_RISK_TIER
FROM RIA_FINANCIAL_INTELLIGENCE.RAW.KYC_PROFILES k
JOIN CUSTOMER_PROFILE p ON p.CUSTOMER_ID = k.CUSTOMER_ID
LEFT JOIN SYNTHETIC_ID_SCORES s ON s.CUSTOMER_ID = k.CUSTOMER_ID;

-- ============================================================================
-- TRANSFER DETAIL: no names or full account data; model fraud score attached
-- ============================================================================
CREATE OR REPLACE VIEW TRANSFER_DETAIL AS
SELECT t.TRANSFER_ID, t.CUSTOMER_ID, t.BENEFICIARY_ID, t.CORRIDOR_ID, co.CORRIDOR_NAME, co.SEND_COUNTRY, co.PAYOUT_COUNTRY, co.REGION AS PAYOUT_REGION,
    co.SEND_CURRENCY, co.PAYOUT_CURRENCY, co.CORRIDOR_RISK_LEVEL, co.CORRIDOR_RISK_SCORE, co.IS_HIGH_RISK_JURISDICTION,
    t.CHANNEL, t.PAYOUT_METHOD, t.FUNDING_TYPE, t.PURPOSE, t.STATUS,
    t.CREATED_AT, t.CREATED_AT::DATE AS TRANSFER_DATE, DATE_TRUNC('WEEK', t.CREATED_AT)::DATE AS TRANSFER_WEEK,
    DATE_TRUNC('MONTH', t.CREATED_AT)::DATE AS TRANSFER_MONTH, DATE_TRUNC('QUARTER', t.CREATED_AT)::DATE AS TRANSFER_QUARTER,
    t.SEND_AMOUNT_USD, t.FEE_USD, t.FX_MARGIN_USD, t.FEE_USD + t.FX_MARGIN_USD AS REVENUE_USD, t.FX_RATE,
    CASE WHEN t.SEND_AMOUNT_USD < 500 THEN 'Under $500' WHEN t.SEND_AMOUNT_USD < 3000 THEN '$500-$2,999'
         WHEN t.SEND_AMOUNT_USD < 10000 THEN '$3,000-$9,999' ELSE '$10,000+' END AS AMOUNT_BAND,
    t.TRAVEL_RULE_REQUIRED, (t.TRAVEL_RULE_REQUIRED AND t.ORIGINATOR_NAME IS NOT NULL AND t.BENEFICIARY_NAME IS NOT NULL) AS TRAVEL_RULE_COMPLETE,
    t.CANCELLED_WITHIN_WINDOW, t.SEND_AGENT_ID, t.PAYOUT_AGENT_ID, a.AGENT_NAME AS SEND_AGENT_NAME,
    c.SEGMENT AS CUSTOMER_SEGMENT, c.SIGNUP_CHANNEL AS CUSTOMER_SIGNUP_CHANNEL, k.RISK_RATING AS CUSTOMER_RISK_RATING,
    t.IS_FRAUD AS CONFIRMED_FRAUD, t.FRAUD_TYPE, t.IS_SCAM_VICTIM AS CONFIRMED_SCAM_VICTIM,
    s.FRAUD_PROB AS FRAUD_PROBABILITY, s.RISK_TIER AS FRAUD_RISK_TIER
FROM RIA_FINANCIAL_INTELLIGENCE.RAW.TRANSFERS t
JOIN RIA_FINANCIAL_INTELLIGENCE.RAW.CORRIDORS co ON co.CORRIDOR_ID = t.CORRIDOR_ID
JOIN RIA_FINANCIAL_INTELLIGENCE.RAW.CUSTOMERS c ON c.CUSTOMER_ID = t.CUSTOMER_ID
JOIN RIA_FINANCIAL_INTELLIGENCE.RAW.KYC_PROFILES k ON k.CUSTOMER_ID = t.CUSTOMER_ID
LEFT JOIN RIA_FINANCIAL_INTELLIGENCE.RAW.AGENT_LOCATIONS a ON a.AGENT_ID = t.SEND_AGENT_ID
LEFT JOIN TRANSFER_FRAUD_SCORES s ON s.TRANSFER_ID = t.TRANSFER_ID;

-- ============================================================================
-- FRAUD LOSS by corridor and month (cohort = transfer month)
-- ============================================================================
CREATE OR REPLACE VIEW FRAUD_LOSS_MONTHLY AS
SELECT v.CORRIDOR_ID, co.CORRIDOR_NAME, co.SEND_COUNTRY, co.PAYOUT_COUNTRY, co.REGION AS PAYOUT_REGION, co.CORRIDOR_RISK_LEVEL,
    v.TRANSFER_MONTH, DATE_TRUNC('QUARTER', v.TRANSFER_MONTH)::DATE AS TRANSFER_QUARTER,
    v.TRANSFER_COUNT, v.VOLUME_USD, v.FRAUD_TRANSFER_COUNT, v.FRAUD_VOLUME_USD,
    COALESCE(l.GROSS_LOSS_USD, 0) AS GROSS_LOSS_USD, COALESCE(l.RECOVERED_USD, 0) AS RECOVERED_USD,
    COALESCE(l.WRITE_OFF_USD, 0) AS WRITE_OFF_USD, COALESCE(l.NET_LOSS_USD, 0) AS NET_LOSS_USD, COALESCE(l.LOSS_COUNT, 0) AS LOSS_COUNT
FROM (SELECT CORRIDOR_ID, DATE_TRUNC('MONTH', CREATED_AT)::DATE AS TRANSFER_MONTH, COUNT(*) AS TRANSFER_COUNT, SUM(SEND_AMOUNT_USD) AS VOLUME_USD,
             COUNT_IF(IS_FRAUD) AS FRAUD_TRANSFER_COUNT, SUM(IFF(IS_FRAUD, SEND_AMOUNT_USD, 0)) AS FRAUD_VOLUME_USD
      FROM RIA_FINANCIAL_INTELLIGENCE.RAW.TRANSFERS GROUP BY 1, 2) v
JOIN RIA_FINANCIAL_INTELLIGENCE.RAW.CORRIDORS co ON co.CORRIDOR_ID = v.CORRIDOR_ID
LEFT JOIN (SELECT t.CORRIDOR_ID, DATE_TRUNC('MONTH', t.CREATED_AT)::DATE AS TRANSFER_MONTH, SUM(fl.GROSS_LOSS_USD) AS GROSS_LOSS_USD,
                  SUM(fl.RECOVERED_USD) AS RECOVERED_USD, SUM(fl.WRITE_OFF_USD) AS WRITE_OFF_USD, SUM(fl.NET_LOSS_USD) AS NET_LOSS_USD, COUNT(*) AS LOSS_COUNT
           FROM RIA_FINANCIAL_INTELLIGENCE.RAW.FRAUD_LOSSES fl JOIN RIA_FINANCIAL_INTELLIGENCE.RAW.TRANSFERS t ON t.TRANSFER_ID = fl.TRANSFER_ID
           GROUP BY 1, 2) l ON l.CORRIDOR_ID = v.CORRIDOR_ID AND l.TRANSFER_MONTH = v.TRANSFER_MONTH;

-- ============================================================================
-- ALERT and CASE detail (aging, backlog, dispositions)
-- ============================================================================
CREATE OR REPLACE VIEW ALERT_DETAIL AS
SELECT a.ALERT_ID, a.CUSTOMER_ID, a.TRANSFER_ID, a.AGENT_ID, a.ALERT_TYPE, a.DETECTION_SOURCE, a.RULE_CODE, a.ALERT_SCORE, a.SEVERITY, a.QUEUE,
    a.CREATED_AT, a.CREATED_AT::DATE AS CREATED_DATE, DATE_TRUNC('MONTH', a.CREATED_AT)::DATE AS CREATED_MONTH, a.STATUS,
    (a.STATUS <> 'Closed') AS IS_OPEN, a.DISPOSITION, a.CLOSED_AT, a.CASE_ID,
    DATEDIFF(DAY, a.CREATED_AT, COALESCE(a.CLOSED_AT, CURRENT_TIMESTAMP())) AS AGE_DAYS,
    (a.STATUS <> 'Closed' AND a.CREATED_AT < DATEADD(DAY, -30, CURRENT_TIMESTAMP())) AS IS_OPEN_OVER_30_DAYS,
    CASE WHEN DATEDIFF(DAY, a.CREATED_AT, COALESCE(a.CLOSED_AT, CURRENT_TIMESTAMP())) <= 7 THEN '0-7 days'
         WHEN DATEDIFF(DAY, a.CREATED_AT, COALESCE(a.CLOSED_AT, CURRENT_TIMESTAMP())) <= 30 THEN '8-30 days'
         WHEN DATEDIFF(DAY, a.CREATED_AT, COALESCE(a.CLOSED_AT, CURRENT_TIMESTAMP())) <= 60 THEN '31-60 days'
         WHEN DATEDIFF(DAY, a.CREATED_AT, COALESCE(a.CLOSED_AT, CURRENT_TIMESTAMP())) <= 90 THEN '61-90 days' ELSE 'Over 90 days' END AS AGE_BUCKET,
    a.ASSIGNED_ANALYST_ID, an.ANALYST_NAME AS ASSIGNED_ANALYST_NAME, (a.ASSIGNED_ANALYST_ID IS NULL) AS IS_UNASSIGNED,
    DATEDIFF(HOUR, a.CREATED_AT, a.ASSIGNED_AT) AS HOURS_TO_ASSIGN, DATEDIFF(HOUR, a.CREATED_AT, a.CLOSED_AT) AS HOURS_TO_CLOSE
FROM RIA_FINANCIAL_INTELLIGENCE.RAW.FRAUD_ALERTS a
LEFT JOIN RIA_FINANCIAL_INTELLIGENCE.RAW.ANALYSTS an ON an.ANALYST_ID = a.ASSIGNED_ANALYST_ID;

CREATE OR REPLACE VIEW CASE_DETAIL AS
SELECT c.CASE_ID, c.CUSTOMER_ID, c.CASE_TYPE, c.QUEUE, c.PRIORITY, c.OPENED_AT, c.OPENED_AT::DATE AS OPENED_DATE,
    DATE_TRUNC('MONTH', c.OPENED_AT)::DATE AS OPENED_MONTH, c.STATUS, (c.STATUS <> 'Closed') AS IS_OPEN, c.DISPOSITION, c.CLOSED_AT,
    DATEDIFF(DAY, c.OPENED_AT, COALESCE(c.CLOSED_AT, CURRENT_TIMESTAMP())) AS AGE_DAYS,
    (c.STATUS <> 'Closed' AND c.OPENED_AT < DATEADD(DAY, -30, CURRENT_TIMESTAMP())) AS IS_OPEN_OVER_30_DAYS,
    c.EXPOSURE_USD, c.SAR_REQUIRED, c.ASSIGNED_ANALYST_ID, an.ANALYST_NAME AS ASSIGNED_ANALYST_NAME,
    COALESCE(al.ALERT_COUNT, 0) AS ALERT_COUNT, COALESCE(ls.NET_LOSS_USD, 0) AS NET_LOSS_USD
FROM RIA_FINANCIAL_INTELLIGENCE.RAW.FRAUD_CASES c
LEFT JOIN RIA_FINANCIAL_INTELLIGENCE.RAW.ANALYSTS an ON an.ANALYST_ID = c.ASSIGNED_ANALYST_ID
LEFT JOIN (SELECT CASE_ID, COUNT(*) AS ALERT_COUNT FROM RIA_FINANCIAL_INTELLIGENCE.RAW.FRAUD_ALERTS WHERE CASE_ID IS NOT NULL GROUP BY CASE_ID) al ON al.CASE_ID = c.CASE_ID
LEFT JOIN (SELECT CASE_ID, SUM(NET_LOSS_USD) AS NET_LOSS_USD FROM RIA_FINANCIAL_INTELLIGENCE.RAW.FRAUD_LOSSES WHERE CASE_ID IS NOT NULL GROUP BY CASE_ID) ls ON ls.CASE_ID = c.CASE_ID;

-- ============================================================================
-- DISPUTE ACTIVITY: chargebacks, ACH returns, refunds and Reg E disputes
-- ============================================================================
CREATE OR REPLACE VIEW DISPUTE_ACTIVITY AS
SELECT u.ITEM_TYPE, u.ITEM_ID, u.TRANSFER_ID, t.CUSTOMER_ID, t.CORRIDOR_ID, co.CORRIDOR_NAME, t.FUNDING_TYPE, t.CHANNEL,
    u.EVENT_AT, u.EVENT_AT::DATE AS EVENT_DATE, DATE_TRUNC('MONTH', u.EVENT_AT)::DATE AS EVENT_MONTH,
    u.AMOUNT_USD, u.REASON, u.REASON_CODE, u.STATUS, u.DAYS_ELAPSED, u.IS_UNAUTHORIZED, u.WITHIN_TIMELINE, u.OUTCOME
FROM (
    SELECT 'Chargeback' AS ITEM_TYPE, CHARGEBACK_ID AS ITEM_ID, TRANSFER_ID, RECEIVED_AT AS EVENT_AT, AMOUNT_USD, REASON, REASON_CODE, STATUS,
           DAYS_FROM_TRANSFER AS DAYS_ELAPSED, (REASON = 'Fraud - Card Not Present') AS IS_UNAUTHORIZED, CAST(NULL AS BOOLEAN) AS WITHIN_TIMELINE, CAST(NULL AS VARCHAR) AS OUTCOME
    FROM RIA_FINANCIAL_INTELLIGENCE.RAW.CHARGEBACKS
    UNION ALL
    SELECT 'ACH Return', RETURN_ID, TRANSFER_ID, RETURNED_AT, AMOUNT_USD, RETURN_REASON, RETURN_CODE, 'Returned', NULL, IS_UNAUTHORIZED, NULL, NULL
    FROM RIA_FINANCIAL_INTELLIGENCE.RAW.ACH_RETURNS
    UNION ALL
    SELECT 'Refund', REFUND_ID, TRANSFER_ID, REQUESTED_AT, AMOUNT_USD, REASON, NULL, IFF(REFUNDED_AT IS NULL, 'Pending', 'Refunded'), DAYS_TO_REFUND,
           (REASON = 'Fraud'), WITHIN_REG_E_TIMELINE, NULL
    FROM RIA_FINANCIAL_INTELLIGENCE.RAW.REFUNDS
    UNION ALL
    SELECT 'Reg E Dispute', d.DISPUTE_ID, d.TRANSFER_ID, d.OPENED_AT, tt.SEND_AMOUNT_USD, d.ERROR_TYPE, NULL, d.STATUS, d.DAYS_TO_RESOLVE,
           (d.ERROR_TYPE = 'Unauthorized'), d.WITHIN_90_DAYS, d.OUTCOME
    FROM RIA_FINANCIAL_INTELLIGENCE.RAW.DISPUTES d JOIN RIA_FINANCIAL_INTELLIGENCE.RAW.TRANSFERS tt ON tt.TRANSFER_ID = d.TRANSFER_ID
) u
JOIN RIA_FINANCIAL_INTELLIGENCE.RAW.TRANSFERS t ON t.TRANSFER_ID = u.TRANSFER_ID
JOIN RIA_FINANCIAL_INTELLIGENCE.RAW.CORRIDORS co ON co.CORRIDOR_ID = t.CORRIDOR_ID;

-- ============================================================================
-- AGENT NETWORK performance with collusion score
-- ============================================================================
CREATE OR REPLACE VIEW AGENT_NETWORK AS
SELECT a.AGENT_ID, a.AGENT_NAME, a.AGENT_TYPE, a.ROLE, a.COUNTRY, a.CITY, a.REGION, a.STATUS, a.ONBOARDED_DATE, a.DAILY_LIMIT_USD,
    a.LAST_AUDIT_DATE, DATEDIFF(DAY, a.LAST_AUDIT_DATE, CURRENT_DATE()) AS DAYS_SINCE_AUDIT, a.AUDIT_RATING, a.TRAINING_COMPLETED,
    a.CONFIRMED_COLLUSION,
    COALESCE(s.TRANSFERS_90D, 0) AS SEND_TRANSFERS_90D, COALESCE(s.VOLUME_90D, 0) AS SEND_VOLUME_90D_USD, s.AVG_AMOUNT AS AVG_SEND_AMOUNT_USD,
    COALESCE(s.NEAR_THRESHOLD_PCT, 0) AS NEAR_THRESHOLD_SHARE_PCT, COALESCE(s.CANCEL_PCT, 0) AS CANCELLATION_RATE_PCT,
    COALESCE(s.CASH_PCT, 0) AS CASH_SHARE_PCT, COALESCE(s.DISTINCT_CUSTOMERS, 0) AS DISTINCT_CUSTOMERS_90D,
    COALESCE(p.PAYOUTS_90D, 0) AS PAYOUT_TRANSFERS_90D, COALESCE(p.PAYOUT_VOLUME_90D, 0) AS PAYOUT_VOLUME_90D_USD,
    cs.COLLUSION_PROB AS COLLUSION_PROBABILITY, cs.RISK_TIER AS COLLUSION_RISK_TIER
FROM RIA_FINANCIAL_INTELLIGENCE.RAW.AGENT_LOCATIONS a
LEFT JOIN (SELECT SEND_AGENT_ID, COUNT(*) AS TRANSFERS_90D, SUM(SEND_AMOUNT_USD) AS VOLUME_90D, AVG(SEND_AMOUNT_USD) AS AVG_AMOUNT,
                  100 * AVG(IFF(SEND_AMOUNT_USD BETWEEN 2500 AND 2999.99 OR SEND_AMOUNT_USD BETWEEN 8500 AND 9999.99, 1, 0)) AS NEAR_THRESHOLD_PCT,
                  100 * AVG(IFF(STATUS = 'Cancelled', 1, 0)) AS CANCEL_PCT, 100 * AVG(IFF(FUNDING_TYPE = 'Cash', 1, 0)) AS CASH_PCT,
                  COUNT(DISTINCT CUSTOMER_ID) AS DISTINCT_CUSTOMERS
           FROM RIA_FINANCIAL_INTELLIGENCE.RAW.TRANSFERS WHERE SEND_AGENT_ID IS NOT NULL AND CREATED_AT >= DATEADD(DAY, -90, CURRENT_TIMESTAMP())
           GROUP BY SEND_AGENT_ID) s ON s.SEND_AGENT_ID = a.AGENT_ID
LEFT JOIN (SELECT PAYOUT_AGENT_ID, COUNT(*) AS PAYOUTS_90D, SUM(SEND_AMOUNT_USD) AS PAYOUT_VOLUME_90D
           FROM RIA_FINANCIAL_INTELLIGENCE.RAW.TRANSFERS WHERE PAYOUT_AGENT_ID IS NOT NULL AND CREATED_AT >= DATEADD(DAY, -90, CURRENT_TIMESTAMP())
           GROUP BY PAYOUT_AGENT_ID) p ON p.PAYOUT_AGENT_ID = a.AGENT_ID
LEFT JOIN AGENT_COLLUSION_SCORES cs ON cs.AGENT_ID = a.AGENT_ID;

-- ============================================================================
-- SANCTIONS SCREENING detail with triage score
-- ============================================================================
CREATE OR REPLACE VIEW SCREENING_DETAIL AS
SELECT sc.SCREENING_ID, sc.TRANSFER_ID, sc.CUSTOMER_ID, sc.SCREENED_PARTY, sc.LIST_SOURCE, sc.MATCHED_ENTRY_NAME, sc.MATCHED_ENTRY_COUNTRY,
    sc.MATCH_SCORE, sc.NAME_SIMILARITY, sc.DOB_MATCH, sc.COUNTRY_MATCH, sc.SECONDARY_ID_MATCH,
    sc.SCREENED_AT, sc.SCREENED_AT::DATE AS SCREENED_DATE, DATE_TRUNC('MONTH', sc.SCREENED_AT)::DATE AS SCREENED_MONTH,
    sc.STATUS, (sc.STATUS = 'Open') AS IS_OPEN, sc.DISPOSITION, sc.DISPOSITIONED_AT, sc.ANALYST_ID, sc.IS_TRUE_MATCH,
    DATEDIFF(HOUR, sc.SCREENED_AT, COALESCE(sc.DISPOSITIONED_AT, CURRENT_TIMESTAMP())) AS HOURS_TO_DISPOSITION,
    t.SEND_AMOUNT_USD, t.CORRIDOR_ID, co.CORRIDOR_NAME, co.PAYOUT_COUNTRY, co.IS_HIGH_RISK_JURISDICTION, k.RISK_RATING AS CUSTOMER_RISK_RATING, k.PEP_FLAG,
    ts.TRUE_MATCH_PROB AS TRUE_MATCH_PROBABILITY, ts.RISK_TIER AS TRIAGE_TIER
FROM RIA_FINANCIAL_INTELLIGENCE.RAW.SANCTIONS_SCREENING sc
JOIN RIA_FINANCIAL_INTELLIGENCE.RAW.TRANSFERS t ON t.TRANSFER_ID = sc.TRANSFER_ID
JOIN RIA_FINANCIAL_INTELLIGENCE.RAW.CORRIDORS co ON co.CORRIDOR_ID = t.CORRIDOR_ID
JOIN RIA_FINANCIAL_INTELLIGENCE.RAW.KYC_PROFILES k ON k.CUSTOMER_ID = sc.CUSTOMER_ID
LEFT JOIN SCREENING_TRIAGE_SCORES ts ON ts.SCREENING_ID = sc.SCREENING_ID;

