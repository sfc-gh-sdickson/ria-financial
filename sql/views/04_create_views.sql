CREATE OR REPLACE VIEW V_AGENT_FEATURES AS
SELECT ag.AGENT_ID,
    s.N::FLOAT AS TRANSFER_COUNT, s.TOTAL_USD::FLOAT AS TOTAL_USD, s.AVG_USD::FLOAT AS AVG_AMOUNT_USD,
