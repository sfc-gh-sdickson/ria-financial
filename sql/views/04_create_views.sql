CREATE OR REPLACE VIEW COMPLIANCE_FILINGS AS
SELECT f.FILING_TYPE, f.FILING_ID, f.CUSTOMER_ID, f.CASE_ID, f.ACTIVITY_TYPE, f.TRIGGER_DATE, DATE_TRUNC('MONTH', f.TRIGGER_DATE)::DATE AS TRIGGER_MONTH,
    f.DUE_DATE, f.FILED_DATE, f.FILING_STATUS, (f.FILED_DATE IS NOT NULL) AS IS_FILED,
    COALESCE(f.DAYS_TO_FILE, DATEDIFF(DAY, f.TRIGGER_DATE, f.FILED_DATE)) AS DAYS_TO_FILE,
    IFF(f.FILED_DATE IS NULL, DATEDIFF(DAY, CURRENT_DATE(), f.DUE_DATE), NULL) AS DAYS_UNTIL_DUE,
    (f.FILED_DATE IS NULL AND f.DUE_DATE < CURRENT_DATE()) AS IS_OVERDUE,
    (f.FILED_DATE IS NULL AND f.DUE_DATE >= CURRENT_DATE() AND f.DUE_DATE <= DATEADD(DAY, 10, CURRENT_DATE())) AS IS_AT_RISK,
    (f.FILED_DATE IS NOT NULL AND f.FILED_DATE <= f.DUE_DATE) AS FILED_ON_TIME, f.AMOUNT_USD
FROM (
    SELECT 'SAR' AS FILING_TYPE, SAR_ID AS FILING_ID, CUSTOMER_ID, CASE_ID, SUSPICIOUS_ACTIVITY_TYPE AS ACTIVITY_TYPE, DETECTION_DATE AS TRIGGER_DATE,
           DUE_DATE, FILED_DATE, FILING_STATUS, DAYS_TO_FILE, AMOUNT_USD
    FROM RIA_FINANCIAL_INTELLIGENCE.RAW.SAR_FILINGS
    UNION ALL
    SELECT 'CTR', CTR_ID, CUSTOMER_ID, NULL, 'Cash over $10,000', BUSINESS_DATE, DUE_DATE, FILED_DATE, FILING_STATUS, NULL, TOTAL_CASH_USD
    FROM RIA_FINANCIAL_INTELLIGENCE.RAW.CTR_FILINGS
) f;

