-- ---------------------------------------------------------------------------
-- Model 5: structuring per customer-week (spine: 2+ transfers and $3,000+ sent)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW V_STRUCTURING_FEATURES AS
WITH wk AS (
    SELECT t.CUSTOMER_ID, DATE_TRUNC('WEEK', t.CREATED_AT)::DATE AS WEEK_START, COUNT(*) AS N, SUM(t.SEND_AMOUNT_USD) AS TOT,
           MAX(t.SEND_AMOUNT_USD) AS MX, MIN(t.SEND_AMOUNT_USD) AS MN, AVG(t.SEND_AMOUNT_USD) AS AV, COALESCE(STDDEV(t.SEND_AMOUNT_USD), 0) AS SD,
           AVG(IFF(t.FUNDING_TYPE = 'Cash', 1, 0)) AS CASH_SHARE,
           COUNT_IF(t.SEND_AMOUNT_USD BETWEEN 2500 AND 2999.99) AS N3K, COUNT_IF(t.SEND_AMOUNT_USD BETWEEN 8500 AND 9999.99) AS N10K,
           COUNT(DISTINCT t.CREATED_AT::DATE) AS DAYS, COUNT(DISTINCT t.SEND_AGENT_ID) AS AGENTS, COUNT(DISTINCT t.BENEFICIARY_ID) AS BENES
    FROM RIA_FINANCIAL_INTELLIGENCE.RAW.TRANSFERS t WHERE t.STATUS <> 'Cancelled' GROUP BY t.CUSTOMER_ID, DATE_TRUNC('WEEK', t.CREATED_AT)::DATE),
     wk2 AS (
    SELECT wk.*,
        AVG(TOT) OVER (PARTITION BY CUSTOMER_ID ORDER BY WEEK_START ROWS BETWEEN 4 PRECEDING AND 1 PRECEDING) AS PRIOR4_AVG,
        COUNT(*) OVER (PARTITION BY CUSTOMER_ID ORDER BY WEEK_START ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING) AS PRIOR_WEEKS
    FROM wk)
SELECT w.CUSTOMER_ID, w.WEEK_START,
    w.TOT::FLOAT AS WEEK_TOTAL_USD, w.N::FLOAT AS TXN_COUNT, w.MX::FLOAT AS MAX_SINGLE_USD, w.MN::FLOAT AS MIN_SINGLE_USD, w.AV::FLOAT AS AVG_SINGLE_USD,
    w.SD::FLOAT AS STD_SINGLE_USD, (w.SD / NULLIF(w.AV, 0))::FLOAT AS CV_SINGLE, w.CASH_SHARE::FLOAT AS CASH_SHARE,
    w.N3K::FLOAT AS NEAR_3K_COUNT, w.N10K::FLOAT AS NEAR_10K_COUNT, (w.N3K / w.N)::FLOAT AS NEAR_3K_SHARE, (w.N10K / w.N)::FLOAT AS NEAR_10K_SHARE,
    w.DAYS::FLOAT AS DISTINCT_DAYS, w.AGENTS::FLOAT AS DISTINCT_AGENTS, w.BENES::FLOAT AS DISTINCT_BENEFICIARIES,
    k.EXPECTED_MONTHLY_USD::FLOAT AS EXPECTED_MONTHLY_USD, (w.TOT / GREATEST(k.EXPECTED_MONTHLY_USD, 1))::FLOAT AS WEEK_VS_EXPECTED_MONTH_RATIO,
    COALESCE(w.PRIOR4_AVG, 0)::FLOAT AS PRIOR_4W_AVG_TOTAL_USD, COALESCE(w.TOT / NULLIF(w.PRIOR4_AVG, 0), 1)::FLOAT AS WEEK_VS_PRIOR_RATIO,
    COALESCE(w.PRIOR_WEEKS, 0)::FLOAT AS PRIOR_ACTIVE_WEEKS,
    CASE k.RISK_RATING WHEN 'High' THEN 3 WHEN 'Medium' THEN 2 ELSE 1 END::FLOAT AS KYC_RISK_NUM,
    r.CONFIRMED_STRUCTURING::INT AS CONFIRMED_STRUCTURING
FROM wk2 w
JOIN RIA_FINANCIAL_INTELLIGENCE.RAW.KYC_PROFILES k ON k.CUSTOMER_ID = w.CUSTOMER_ID
LEFT JOIN RIA_FINANCIAL_INTELLIGENCE.RAW.STRUCTURING_REVIEWS r ON r.CUSTOMER_ID = w.CUSTOMER_ID AND r.WEEK_START = w.WEEK_START
WHERE w.N >= 2 AND w.TOT >= 3000;

-- ---------------------------------------------------------------------------
-- Model 6: agent collusion per send-capable agent location
