-- ---------------------------------------------------------------------------
-- Model 9: network links per customer (unsupervised; no label)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW V_RING_FEATURES AS
WITH ph AS (
    SELECT CUSTOMER_ID, PHONE, COUNT(*) OVER (PARTITION BY PHONE) AS PHONE_GROUP_SIZE, MIN(CUSTOMER_ID) OVER (PARTITION BY PHONE) AS PHONE_GROUP_KEY
    FROM RIA_FINANCIAL_INTELLIGENCE.RAW.CUSTOMERS),
     dv AS (
    SELECT s.CUSTOMER_ID, COUNT(DISTINCT s.DEVICE_ID) AS DEVICES, MAX(dc.N) AS MAX_DEVICE_CUSTOMERS
    FROM RIA_FINANCIAL_INTELLIGENCE.RAW.APP_SESSIONS s
    JOIN (SELECT DEVICE_ID, COUNT(DISTINCT CUSTOMER_ID) AS N FROM RIA_FINANCIAL_INTELLIGENCE.RAW.APP_SESSIONS GROUP BY DEVICE_ID) dc ON dc.DEVICE_ID = s.DEVICE_ID
    GROUP BY s.CUSTOMER_ID),
     ip AS (
    SELECT s.CUSTOMER_ID, MAX(ic.N) AS MAX_IP_CUSTOMERS, COUNT(DISTINCT s.IP_ADDRESS) AS IPS
    FROM RIA_FINANCIAL_INTELLIGENCE.RAW.APP_SESSIONS s
    JOIN (SELECT IP_ADDRESS, COUNT(DISTINCT CUSTOMER_ID) AS N FROM RIA_FINANCIAL_INTELLIGENCE.RAW.APP_SESSIONS GROUP BY IP_ADDRESS) ic ON ic.IP_ADDRESS = s.IP_ADDRESS
    GROUP BY s.CUSTOMER_ID),
     bn AS (
    SELECT pr.CUSTOMER_ID, SUM(bs.SENDERS - 1) AS SHARED_SENDERS, MAX(bs.SENDERS - 1) AS MAX_SHARED_SENDERS, COUNT(*) AS BENES
    FROM (SELECT DISTINCT CUSTOMER_ID, BENEFICIARY_ID FROM RIA_FINANCIAL_INTELLIGENCE.RAW.TRANSFERS) pr
    JOIN (SELECT BENEFICIARY_ID, COUNT(DISTINCT CUSTOMER_ID) AS SENDERS FROM RIA_FINANCIAL_INTELLIGENCE.RAW.TRANSFERS GROUP BY BENEFICIARY_ID) bs ON bs.BENEFICIARY_ID = pr.BENEFICIARY_ID
    GROUP BY pr.CUSTOMER_ID),
     tx AS (
    SELECT CUSTOMER_ID, COUNT(*) AS N, SUM(SEND_AMOUNT_USD) AS V, COUNT_IF(CREATED_AT >= DATEADD(DAY, -90, CURRENT_TIMESTAMP())) AS N90 FROM RIA_FINANCIAL_INTELLIGENCE.RAW.TRANSFERS GROUP BY CUSTOMER_ID)
SELECT c.CUSTOMER_ID, ph.PHONE_GROUP_KEY, ph.PHONE_GROUP_SIZE,
    (ph.PHONE_GROUP_SIZE - 1)::FLOAT AS PHONE_SHARED_COUNT,
    COALESCE(dv.DEVICES, 0)::FLOAT AS DEVICE_COUNT, GREATEST(COALESCE(dv.MAX_DEVICE_CUSTOMERS, 1) - 1, 0)::FLOAT AS DEVICE_SHARED_MAX,
    GREATEST(COALESCE(ip.MAX_IP_CUSTOMERS, 1) - 1, 0)::FLOAT AS IP_SHARED_MAX, COALESCE(ip.IPS, 0)::FLOAT AS IP_COUNT,
    COALESCE(bn.SHARED_SENDERS, 0)::FLOAT AS BENE_SHARED_SENDERS_TOTAL, COALESCE(bn.MAX_SHARED_SENDERS, 0)::FLOAT AS BENE_SHARED_SENDERS_MAX,
    COALESCE(bn.BENES, 0)::FLOAT AS BENEFICIARY_COUNT,
    DATEDIFF(DAY, c.SIGNUP_DATE, CURRENT_DATE())::FLOAT AS ACCOUNT_AGE_DAYS,
    COALESCE(tx.N, 0)::FLOAT AS TRANSFER_COUNT, COALESCE(tx.V, 0)::FLOAT AS TRANSFER_VOLUME_USD, COALESCE(tx.N90, 0)::FLOAT AS TRANSFERS_90D,
    IFF(k.PHONE_IS_VOIP, 1, 0)::FLOAT AS PHONE_IS_VOIP, k.EMAIL_AGE_DAYS::FLOAT AS EMAIL_AGE_DAYS, k.ADDRESS_SHARED_COUNT::FLOAT AS ADDRESS_SHARED_COUNT
FROM RIA_FINANCIAL_INTELLIGENCE.RAW.CUSTOMERS c
JOIN ph ON ph.CUSTOMER_ID = c.CUSTOMER_ID
JOIN RIA_FINANCIAL_INTELLIGENCE.RAW.KYC_PROFILES k ON k.CUSTOMER_ID = c.CUSTOMER_ID
LEFT JOIN dv ON dv.CUSTOMER_ID = c.CUSTOMER_ID
LEFT JOIN ip ON ip.CUSTOMER_ID = c.CUSTOMER_ID
LEFT JOIN bn ON bn.CUSTOMER_ID = c.CUSTOMER_ID
LEFT JOIN tx ON tx.CUSTOMER_ID = c.CUSTOMER_ID;

