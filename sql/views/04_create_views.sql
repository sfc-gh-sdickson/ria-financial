           FROM RIA_FINANCIAL_INTELLIGENCE.RAW.TRANSFERS GROUP BY CUSTOMER_ID) t ON t.CUSTOMER_ID = p.CUSTOMER_ID
LEFT JOIN (SELECT CUSTOMER_ID, COUNT_IF(STATUS <> 'Closed') AS OPEN_ALERTS FROM RIA_FINANCIAL_INTELLIGENCE.RAW.FRAUD_ALERTS GROUP BY CUSTOMER_ID) al ON al.CUSTOMER_ID = p.CUSTOMER_ID
LEFT JOIN (SELECT CUSTOMER_ID, COUNT_IF(STATUS <> 'Closed') AS OPEN_CASES, COUNT(*) AS TOTAL_CASES FROM RIA_FINANCIAL_INTELLIGENCE.RAW.FRAUD_CASES GROUP BY CUSTOMER_ID) cs ON cs.CUSTOMER_ID = p.CUSTOMER_ID
