/*=============================================================================
  Ria Financial Intelligence Agent
  Step 4: Analytical Views, ML Feature Views and Model Score Tables

  Execution Order: 4 of 9
  Description:
    - Model score tables (CREATE IF NOT EXISTS, never dropped) and the
      ML.MODEL_REGISTRY inventory table
    - Masked, agent-safe analytical views: CUSTOMER_PROFILE, CUSTOMER_360,
      FRAUD_360, KYC_DETAIL, TRANSFER_DETAIL, FRAUD_LOSS_MONTHLY, ALERT_DETAIL,
      CASE_DETAIL, DISPUTE_ACTIVITY, AGENT_NETWORK, SCREENING_DETAIL,
