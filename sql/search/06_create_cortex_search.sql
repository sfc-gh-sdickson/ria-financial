/*=============================================================================
  Ria Financial Intelligence Agent
  Step 6: Cortex Search Services

  Execution Order: 6 of 9
  Description: Six Cortex Search services for retrieval over fraud typology
               guides, investigator case notes, SAR narratives, compliance
               policies, customer complaints and NPS survey comments.
               Only turns on change tracking on the source tables; it does
               not create or modify any data.
=============================================================================*/

USE DATABASE RIA_FINANCIAL_INTELLIGENCE;
USE SCHEMA ANALYTICS;
USE WAREHOUSE RIA_FINANCIAL_WH;

ALTER TABLE RIA_FINANCIAL_INTELLIGENCE.RAW.FRAUD_TYPOLOGIES SET CHANGE_TRACKING = TRUE;
ALTER TABLE RIA_FINANCIAL_INTELLIGENCE.RAW.CASE_NOTES SET CHANGE_TRACKING = TRUE;
ALTER TABLE RIA_FINANCIAL_INTELLIGENCE.RAW.FRAUD_CASES SET CHANGE_TRACKING = TRUE;
ALTER TABLE RIA_FINANCIAL_INTELLIGENCE.RAW.SAR_FILINGS SET CHANGE_TRACKING = TRUE;
ALTER TABLE RIA_FINANCIAL_INTELLIGENCE.RAW.POLICY_DOCUMENTS SET CHANGE_TRACKING = TRUE;
ALTER TABLE RIA_FINANCIAL_INTELLIGENCE.RAW.COMPLAINTS SET CHANGE_TRACKING = TRUE;
ALTER TABLE RIA_FINANCIAL_INTELLIGENCE.RAW.NPS_SURVEYS SET CHANGE_TRACKING = TRUE;

CREATE OR REPLACE CORTEX SEARCH SERVICE RIA_TYPOLOGY_SEARCH
  ON CONTENT
  ATTRIBUTES TYPOLOGY, CATEGORY
  WAREHOUSE = RIA_FINANCIAL_WH
  TARGET_LAG = '1 day'
  COMMENT = 'Fraud and AML typology guides, red flags, investigation playbooks and regulator advisories'
AS
  SELECT DOC_ID, TITLE, TYPOLOGY, CATEGORY, UPDATED_AT, CONTENT
  FROM RIA_FINANCIAL_INTELLIGENCE.RAW.FRAUD_TYPOLOGIES;

CREATE OR REPLACE CORTEX SEARCH SERVICE RIA_CASE_NOTES_SEARCH
  ON NOTE_TEXT
  ATTRIBUTES CASE_TYPE, PRIORITY, CASE_STATUS, QUEUE
  WAREHOUSE = RIA_FINANCIAL_WH
  TARGET_LAG = '1 day'
  COMMENT = 'Investigator case notes with the case type, priority, status and queue'
AS
  SELECT n.NOTE_ID, n.CASE_ID, c.CUSTOMER_ID, c.CASE_TYPE, c.PRIORITY, c.STATUS AS CASE_STATUS, c.QUEUE, n.CREATED_AT, n.NOTE_TEXT
  FROM RIA_FINANCIAL_INTELLIGENCE.RAW.CASE_NOTES n
  JOIN RIA_FINANCIAL_INTELLIGENCE.RAW.FRAUD_CASES c ON c.CASE_ID = n.CASE_ID;

CREATE OR REPLACE CORTEX SEARCH SERVICE RIA_SAR_NARRATIVE_SEARCH
  ON NARRATIVE
  ATTRIBUTES SUSPICIOUS_ACTIVITY_TYPE, FILING_STATUS
  WAREHOUSE = RIA_FINANCIAL_WH
  TARGET_LAG = '1 day'
  COMMENT = 'Synthetic SAR narratives with the suspicious activity type and filing status'
AS
  SELECT SAR_ID, CASE_ID, CUSTOMER_ID, SUSPICIOUS_ACTIVITY_TYPE, FILING_STATUS, DETECTION_DATE, DUE_DATE, NARRATIVE
  FROM RIA_FINANCIAL_INTELLIGENCE.RAW.SAR_FILINGS;

CREATE OR REPLACE CORTEX SEARCH SERVICE RIA_POLICY_SEARCH
  ON CONTENT
  ATTRIBUTES POLICY_AREA, REGULATION
  WAREHOUSE = RIA_FINANCIAL_WH
  TARGET_LAG = '1 day'
  COMMENT = 'Compliance and fraud policies and procedures by policy area and regulation'
AS
  SELECT DOC_ID, TITLE, POLICY_AREA, REGULATION, VERSION, EFFECTIVE_DATE, OWNER, CONTENT
  FROM RIA_FINANCIAL_INTELLIGENCE.RAW.POLICY_DOCUMENTS;

CREATE OR REPLACE CORTEX SEARCH SERVICE RIA_COMPLAINT_SEARCH
  ON COMPLAINT_TEXT
  ATTRIBUTES CATEGORY, CHANNEL, STATUS, CFPB_ESCALATED
  WAREHOUSE = RIA_FINANCIAL_WH
  TARGET_LAG = '1 day'
  COMMENT = 'Customer complaints including CFPB escalations'
AS
  SELECT COMPLAINT_ID, CUSTOMER_ID, TRANSFER_ID, CATEGORY, CHANNEL, STATUS, CFPB_ESCALATED::VARCHAR AS CFPB_ESCALATED, SUBMITTED_AT, COMPLAINT_TEXT
  FROM RIA_FINANCIAL_INTELLIGENCE.RAW.COMPLAINTS;

CREATE OR REPLACE CORTEX SEARCH SERVICE RIA_FEEDBACK_SEARCH
  ON COMMENT_TEXT
  ATTRIBUTES NPS_CATEGORY
  WAREHOUSE = RIA_FINANCIAL_WH
  TARGET_LAG = '1 day'
  COMMENT = 'NPS survey verbatim comments'
AS
  SELECT SURVEY_ID, CUSTOMER_ID, NPS_CATEGORY, NPS_SCORE, SURVEY_DATE, COMMENT_TEXT
  FROM RIA_FINANCIAL_INTELLIGENCE.RAW.NPS_SURVEYS
  WHERE COMMENT_TEXT IS NOT NULL;
